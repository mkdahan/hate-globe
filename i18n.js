function t(key) {
  const lang = (typeof state !== "undefined" && state.lang) || "he";
  const pack = I18N[lang] || I18N.he;
  return pack[key] != null ? pack[key] : (I18N.he[key] || key);
}
function tf(key, vars) {
  let s = t(key);
  if (vars) for (const k in vars) s = s.replaceAll("{" + k + "}", vars[k]);
  return s;
}
